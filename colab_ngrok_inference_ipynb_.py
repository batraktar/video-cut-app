TASK_QUEUE_MAX = 2  # <= ОБМЕЖЕННЯ, щоб не впасти
task_queue = queue.Queue(maxsize=TASK_QUEUE_MAX)

results_store = {}  # task_id -> result / status


def extract_frames(video_path, out_dir, fps, size):
    out_dir.mkdir(parents=True, exist_ok=True)
    pattern = out_dir / '%06d.jpg'
    vf = f'fps={fps},scale={size}:-1'
    cmd = [
        'ffmpeg', '-hide_banner', '-loglevel', 'error',
        '-i', str(video_path),
        '-vf', vf,
        '-q:v', '2',
        str(pattern)
    ]
    subprocess.run(cmd, check=True)


def normalize_label(label):
    value = str(label or "").strip().lower().replace("-", "_").replace(" ", "_")
    if "thermal" in value and "analog" in value:
        return "thermal_analog"
    if "thermal" in value and "digital" in value:
        return "thermal_digital"
    if "analog" in value:
        return "analog"
    if "digital" in value:
        return "digital"
    return value


def build_segments(labels, fps, min_duration):
    if not labels:
        return {}

    segments = {}
    start = 0
    current = labels[0]

    for i in range(1, len(labels)):
        if labels[i] != current:
            duration = (i - start) / fps
            if duration >= min_duration:
                segments.setdefault(current, []).append({
                    "start": round(start / fps, 2),
                    "end": round(i / fps, 2),
                })
            start = i
            current = labels[i]

    duration = (len(labels) - start) / fps
    if duration >= min_duration:
        segments.setdefault(current, []).append({
            "start": round(start / fps, 2),
            "end": round(len(labels) / fps, 2),
        })

    return segments


def process_video(task):
    task_id = task["id"]
    results_store[task_id]["status"] = "processing"

    video_path = task["video"]
    fps = task["fps"]
    size = task["size"]
    min_duration = task["min_duration"]

    with tempfile.TemporaryDirectory() as tmp:
        frames_dir = Path(tmp) / "frames"
        extract_frames(video_path, frames_dir, fps, size)
        frames = sorted(frames_dir.glob("*.jpg"))
        if not frames:
            raise RuntimeError(
                "FFmpeg extracted 0 frames. Check that the queued video still exists and is readable."
            )

        results_store[task_id]["frame_count"] = len(frames)

        labels = []
        BATCH = 32

        for i in range(0, len(frames), BATCH):
            batch = frames[i:i+BATCH]
            results = model.predict(
                [str(p) for p in batch],
                verbose=False
            )
            for r in results:
                if r.probs is None:
                    raise RuntimeError(
                        "The loaded YOLO model is not a classification model: result.probs is empty."
                    )
                labels.append(normalize_label(model.names[int(r.probs.top1)]))

        segments = build_segments(labels, fps, min_duration)

    results_store[task_id]["status"] = "done"
    results_store[task_id]["result"] = segments
    results_store[task_id]["label_counts"] = dict(Counter(labels))


def gpu_worker():
    while True:
        task = task_queue.get()
        try:
            process_video(task)
        except Exception as e:
            results_store[task["id"]]["status"] = "error"
            results_store[task["id"]]["error"] = str(e)
        finally:
            try:
                Path(task["video"]).unlink(missing_ok=True)
            except Exception:
                pass
            task_queue.task_done()


# стартуємо ОДИН GPU worker
threading.Thread(target=gpu_worker, daemon=True).start()
print("GPU worker started")

app = Flask(__name__)
CORS(app)


@app.get("/health")
def health():
    return jsonify({
        "ok": True,
        "queue_size": task_queue.qsize(),
        "queue_max": TASK_QUEUE_MAX
    })


@app.post("/predict")
def predict():
    if task_queue.full():
        return jsonify({
            "ok": False,
            "error": "server_busy"
        }), 429

    if "video" not in request.files:
        return jsonify({ "ok": False, "error": "missing_video" }), 400

    file = request.files["video"]

    fps = float(request.form.get("fps", DEFAULT_FPS))
    size = int(request.form.get("size", DEFAULT_SIZE))
    min_duration = float(request.form.get("min_duration", DEFAULT_MIN_DURATION))

    task_id = f"task_{uuid.uuid4().hex[:16]}"

    suffix = Path(file.filename or "video.mp4").suffix or ".mp4"
    file_descriptor, stored_name = tempfile.mkstemp(
        prefix=f"{task_id}_",
        suffix=suffix,
        dir=UPLOAD_DIR
    )
    os.close(file_descriptor)
    video_path = Path(stored_name)

    try:
        file.save(video_path)
        results_store[task_id] = {
            "status": "queued",
            "file_name": Path(file.filename or "video.mp4").name
        }

        task_queue.put_nowait({
            "id": task_id,
            "video": video_path,
            "fps": fps,
            "size": size,
            "min_duration": min_duration
        })
    except queue.Full:
        video_path.unlink(missing_ok=True)
        results_store.pop(task_id, None)
        return jsonify({
            "ok": False,
            "error": "server_busy"
        }), 429
    except Exception:
        video_path.unlink(missing_ok=True)
        results_store.pop(task_id, None)
        raise

    return jsonify({
        "ok": True,
        "task_id": task_id,
        "status": "queued"
    }), 202


@app.get("/result/<task_id>")
def get_result(task_id):
    if task_id not in results_store:
        return jsonify({ "ok": False, "error": "not_found" }), 404

    return jsonify({
        "ok": True,
        **results_store[task_id]
    })


